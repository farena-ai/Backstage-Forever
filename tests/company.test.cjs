"use strict";
const test = require("node:test");
const assert = require("node:assert/strict");
const { buildCompany } = require("../src/core/company.cjs");
const { defaultState } = require("../src/core/validation.cjs");
const { applyJourneyAction, reconcileJourneys } = require("../src/core/journeys.cjs");
const ai = require("../src/core/providers.cjs");
const at = "2026-01-01T00:00:00.000Z", later = "2026-01-02T00:00:00.000Z";
const profile = (id, extra = {}) => ({ id, name: id, realm: "Synthetic", className: "Mage", level: 10, notes: "PRIVATE_NOTE_SENTINEL", goals: [], ...extra });
const sourced = (id, extra = {}) => profile(id, { source: {kind:"wow-addon",id:"PRIVATE_SOURCE_SENTINEL",updatedAt:at}, clientBuild:"1.15.8.64000", ...extra });
const state = (profiles) => ({...defaultState(),profiles,activeProfileId:profiles[0]?.id??null});
const q = {id:1061,title:"A saved quest",complete:true,objectives:[]};
test("company counts only actually observed logs, preserves unknown and zero-capacity bags, and never mutates", () => {
  const input = state([profile("manual",{quests:[]}),sourced("unknown"),sourced("empty",{quests:[],readiness:{bags:{free:0,total:0}}}),sourced("ready",{quests:[q],readiness:{bags:{free:2,total:20},equipment:[]}})]);
  const before = structuredClone(input), company = buildCompany(input,{now:Date.parse(later)});
  assert.equal(company.characters.length,4);
  assert.deepEqual(company.totals,{characters:4,observedProfiles:3,questLogsKnown:2,questLogsUnknown:2,quests:1,ready:1,goalsPending:0});
  assert.equal(company.characters[0].quests.known,false);
  assert.equal(company.characters[1].quests.count,null);
  assert.equal(company.characters[2].quests.count,0);
  assert.equal(company.characters[2].bags,null);
  assert.deepEqual(company.characters[3].bags,{free:2,total:20});
  assert.deepEqual(input,before);
  assert.doesNotMatch(JSON.stringify(company),/PRIVATE_NOTE_SENTINEL|PRIVATE_SOURCE_SENTINEL|sourceHash|endpoint|apiKey/);
});
test("saved freshness, history, equipment and deterministic recommendation remain local and do not select", () => {
  const input = state([sourced("z",{quests:[q],history:{recent:[],completedIdsKnown:false},readiness:{equipment:[{slot:16,itemId:123,name:"Saved staff"}]}}),sourced("a",{quests:[q],history:{recent:[],completedIdsKnown:true,completedIds:[]}}),profile("goals",{goals:Array.from({length:5},(_,i)=>({id:String(i),text:`PRIVATE_GOAL_${i}`,done:i===4}))})]);
  const out = buildCompany(input,{now:Date.parse(later)+1});
  assert.equal(out.characters[0].source.freshness,"old");
  assert.equal(out.characters[0].source.savedAt,at);
  assert.equal(out.characters[0].history.known,false);
  assert.equal(out.characters[1].history.completedCount,0);
  assert.equal(out.characters[2].goals.previews.length,3);
  assert.equal(out.characters[0].equipment[0].name,"Saved staff");
  assert.equal(out.recommendation.profileId,"a");
  assert.equal(out.recommendation.reason,"ready-turn-ins");
  assert.equal(input.activeProfileId,"z");
  input.profiles[0].quests=[]; input.profiles[1].quests=[];
  assert.equal(buildCompany(input).recommendation.reason,"unfinished-goals");
  input.profiles[2].goals=[];
  assert.equal(buildCompany(input).recommendation,null);
  const publicContext = ai.profileContext(input,"goals",true);
  assert.doesNotMatch(JSON.stringify(publicContext),/PRIVATE_GOAL_|PRIVATE_NOTE_SENTINEL/);
});
test("journey read model separates ready/manual/observed completion from mismatch and orphan tracking", () => {
  let input=state([sourced("p",{quests:[q],history:{recent:[],completedIdsKnown:true,completedIds:[]}})]), seq=0;
  const act=a=>input=applyJourneyAction(input,a,{now:Date.parse(at),id:()=>`id-${++seq}`});
  act({type:"create",title:"PRIVATE_JOURNEY",template:"blank"}); const jid=input.journeys[0].id;
  act({type:"add-quest",journeyId:jid,profileId:"p",questId:1061});
  let step=buildCompany(input).journeys[0].steps[0];
  assert.equal(step.completion,"pending"); assert.equal(step.ready,true); assert.equal(step.tracking,"tracked");
  assert.deepEqual(Object.keys(step.quest).sort(),["build","id"]);
  assert.equal(step.baselineSavedAt,at);
  act({type:"set-done",journeyId:jid,stepId:step.id,done:true});
  assert.equal(buildCompany(input).journeys[0].steps[0].completion,"manual");
  input.profiles[0].source.updatedAt=later; input.profiles[0].history.completedIds=[1061];
  input.journeys=reconcileJourneys(input.journeys,input.profiles);
  input.profiles[0].clientBuild="1.15.9.64001";
  step=buildCompany(input).journeys[0].steps[0];
  assert.equal(step.completion,"observed"); assert.equal(step.tracking,"build-mismatch");
  assert.equal(step.observed.historical,true); assert.equal(step.observed.build,"1.15.8.64000");
  assert.match(step.sourceLabel,/Historical/);
  assert.doesNotMatch(JSON.stringify(step),/sourceHash|PRIVATE_SOURCE_SENTINEL/);
  assert.doesNotMatch(ai.profileContext(input,"p",true),/PRIVATE_JOURNEY|sourceHash|PRIVATE_NOTE_SENTINEL/);
  input.profiles[0].clientBuild="1.15.8.64000"; input.profiles[0].source.id="changed";
  assert.equal(buildCompany(input).journeys[0].steps[0].tracking,"identity-mismatch");
  input.profiles=[]; input.activeProfileId=null;
  step=buildCompany(input).journeys[0].steps[0];
  assert.equal(step.tracking,"orphan"); assert.equal(step.completion,"observed"); assert.equal(step.observed.historical,true);
  assert.doesNotMatch(JSON.stringify(ai.profileContext(input,null,false)),/PRIVATE_JOURNEY/);
});

test("company freshness labels future/unknown saves and detached output keeps bounded local facts",()=>{
  const input=state([sourced("future",{quests:[],readiness:{equipment:[]}}),profile("manual")]);
  const out=buildCompany(input,{now:Date.parse(at)-1});
  assert.equal(out.characters[0].source.freshness,"future");
  assert.equal(out.characters[0].source.ageMs,-1);
  assert.equal(out.characters[1].source.savedAt,null);
  assert.equal(out.characters[1].source.freshness,"unknown");
  out.characters[0].equipment.push({slot:1,itemId:1});assert.deepEqual(input.profiles[0].readiness.equipment,[]);
  assert.throws(()=>buildCompany(input,{now:NaN}));
  assert.throws(()=>buildCompany({...input,profiles:Array(101).fill(input.profiles[0])}));
});
