"use strict";
// Offline build tool (0.53, roadmap 4.3): turns the reviewed dictionaries in data/i18n/<lang>.json into
// the app's src/renderer/locales/<lang>.js and the addon's BackstageForeverLocale.lua. --check verifies.
// Every data/i18n/<lang>.json is compiled (roadmap P1); the file name is the two-letter language code.
// Dictionary: { version: 1, name: "Deutsch", machineNote: "maschinell übersetzt", machineTranslated: true,
//   app: { en: de }, appTemplates: { en: de }, addon: { plain: { en: de }, templates: { en: de } } }
// name is the language's own name (shown in the app's language list); machineNote says "machine-translated" in it.
// Addon templates use Lua format codes (%s %d %02d %.1f); they become anchored patterns whose captures
// fill the translation in the same order.
const fs = require("node:fs");
const path = require("node:path");
const root = path.join(__dirname, "..");
// The game's locale codes each language serves (GetLocale()). A dictionary may override this with "gameLocales".
const GAME_LOCALES = { de: ["deDE"], fr: ["frFR"], es: ["esES", "esMX"], it: ["itIT"], pt: ["ptBR", "ptPT"], ru: ["ruRU"], ko: ["koKR"], zh: ["zhCN"] };
const LANG_CODES = fs.readdirSync(path.join(root, "data", "i18n")).filter((f) => /^[a-z]{2}\.json$/.test(f)).map((f) => f.slice(0, 2)).sort();
const luaString = (value) => '"' + [...Buffer.from(String(value), "utf8")].map((b) => (b >= 32 && b <= 126 && b !== 34 && b !== 92 ? String.fromCharCode(b) : "\\" + String(b).padStart(3, "0"))).join("") + '"';
const CODE = /%(?:0?\d*)?(?:\.\d+)?[sdf]/g;
/** Lua pattern for a format template: literal parts escaped, each code a capture. */
function luaPattern(template) {
  let out = "^", last = 0;
  for (const m of template.matchAll(CODE)) {
    out += template.slice(last, m.index).replace(/[\^$()%.[\]*+\-?]/g, "%$&");
    out += m[0].endsWith("s") ? "(.-)" : m[0].endsWith("d") ? "(%-?%d+)" : "(%-?[%d%.]+)";
    last = m.index + m[0].length;
  }
  return out + template.slice(last).replace(/[\^$()%.[\]*+\-?]/g, "%$&") + "$";
}
/** The translation as a gsub replacement: % escaped, codes become %1, %2… in order. */
function luaReplacement(translation) {
  let n = 0;
  return translation.replace(/%/g, "%%").replace(/%%(?:0?\d*)?(?:\.\d+)?[sdf]/g, () => `%${++n}`);
}
/** App sentence template ("Hand in {#0} finished quests") as an anchored RegExp source. {n} captures any text,
 * {#n} only a number-like run (digits, ., ,, :, /, %, –), so "{#0} of {#1}" never swallows a name like "Secrets of the Dreamers". */
function appPattern(template) {
  return "^" + template.split(/(\{#?\d+\})/).map((part) => (/^\{#\d+\}$/.test(part) ? "([0-9][0-9.,:/%–-]*)" : /^\{\d+\}$/.test(part) ? "(.+?)" : part.replace(/[\\^$.*+?()[\]{}|]/g, "\\$&"))).join("") + "$";
}
function compile(lang) {
  const dict = JSON.parse(fs.readFileSync(path.join(root, "data", "i18n", `${lang}.json`), "utf8"));
  const app = Object.fromEntries(Object.entries(dict.app || {}).filter(([k, v]) => typeof v === "string" && v.trim() && k !== v).sort(([a], [b]) => a.localeCompare(b)));
  // Templates: [pattern, translation, placeholder order] with the most literal text first, so the most specific wins.
  const ph = (s) => (s.match(/\{#?\d+\}/g) || []).map((x) => x.replace("#", "")).sort().join(" ");
  const appTemplates = Object.entries(dict.appTemplates || {}).filter(([k, v]) => typeof v === "string" && v.trim() && ph(k) && ph(k) === ph(v))
    .sort(([a], [b]) => b.replace(/\{#?\d+\}/g, "").length - a.replace(/\{#?\d+\}/g, "").length || a.localeCompare(b))
    .map(([k, v]) => [appPattern(k), v, (k.match(/\{#?\d+\}/g) || []).map((x) => Number(x.replace(/\D/g, "")))]);
  const gameLocales = Array.isArray(dict.gameLocales) && dict.gameLocales.length ? dict.gameLocales : GAME_LOCALES[lang];
  if (!gameLocales || !gameLocales.every((x) => /^[a-z]{2}[A-Z]{2}$/.test(x))) throw new Error(`data/i18n/${lang}.json: no game locale codes known for "${lang}"; add "gameLocales": ["xxXX"].`);
  if (typeof dict.name !== "string" || !dict.name.trim()) throw new Error(`data/i18n/${lang}.json: "name" (the language's own name) is missing.`);
  const meta = { name: dict.name.trim(), machineTranslated: dict.machineTranslated === true, machineNote: typeof dict.machineNote === "string" && dict.machineNote.trim() ? dict.machineNote.trim() : "machine-translated", gameLocales };
  const U = lang.toUpperCase();
  const js = `"use strict";\n// Generated by scripts/build-locales.cjs from data/i18n/${lang}.json${dict.machineTranslated ? " (machine-translated, reviewed by spot checks)" : ""}.\nwindow.BF_LOCALE_${U} = ${JSON.stringify(app, null, 1)};\nwindow.BF_LOCALE_${U}_TEMPLATES = ${JSON.stringify(appTemplates, null, 1)};\nwindow.BF_LOCALE_${U}_META = ${JSON.stringify(meta)};\n`;
  const plain = Object.entries(dict.addon?.plain || {}).filter(([k, v]) => typeof v === "string" && v.trim() && k !== v).sort(([a], [b]) => a.localeCompare(b));
  const templates = Object.entries(dict.addon?.templates || {}).filter(([k, v]) => typeof v === "string" && (k.match(CODE) || []).length === (v.match(CODE) || []).length && (k.match(CODE) || []).length > 0)
    .sort(([a], [b]) => b.length - a.length || a.localeCompare(b)); // longest first: the most specific pattern wins
  return { js, plain, templates, meta };
}
function luaFile(all) {
  const blocks = Object.entries(all).map(([lang, c]) => `if ${c.meta.gameLocales.map((code) => `L==${luaString(code)}`).join(" or ")} then -- ${lang}\n    plain={\n${c.plain.map(([k, v]) => `        [${luaString(k)}]=${luaString(v)},`).join("\n")}\n    }\n    patterns={\n${c.templates.map(([k, v]) => `        {${luaString(luaPattern(k))},${luaString(luaReplacement(v))}},`).join("\n")}\n    }\nend`).join("\n");
  return `-- Generated by scripts/build-locales.cjs from data/i18n/*.json (0.53, roadmap 4.3); data and one lookup.
-- The addon's messages are written in English; BackstageForeverTr swaps them for the game's language
-- when a translation exists (machine translations are marked as such in the app), and returns them unchanged
-- otherwise. Only the block for the game's own language is built; the rest is skipped.
local L=type(GetLocale)=='function' and GetLocale() or 'enUS'
local plain,patterns={},{}
${blocks}
BackstageForeverLocaleName=L
BackstageForeverTranslated=next(plain)~=nil or #patterns>0
function BackstageForeverTr(s)
    if type(s)~='string' or s=='' or not BackstageForeverTranslated then return s end
    local v=plain[s]
    if v then return v end
    for i=1,#patterns do
        local p=patterns[i]
        local ok,r,n=pcall(string.gsub,s,p[1],p[2],1)
        if ok and n and n>0 then return r end
    end
    return s
end
`;
}
const compiled = Object.fromEntries(LANG_CODES.map((l) => [l, compile(l)]));
{ // one game locale, one language
  const seen = new Map();
  for (const [l, c] of Object.entries(compiled)) for (const code of c.meta.gameLocales) { if (seen.has(code)) throw new Error(`${code} is claimed by both ${seen.get(code)} and ${l}.`); seen.set(code, l); }
}
const outputs = Object.fromEntries([
  ...Object.entries(compiled).map(([l, c]) => [path.join(root, "src", "renderer", "locales", `${l}.js`), c.js]),
  [path.join(root, "addon", "BackstageForever", "BackstageForeverLocale.lua"), luaFile(compiled)],
]);
if (process.argv.includes("--check")) {
  for (const [file, text] of Object.entries(outputs)) {
    const now = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : "";
    if (now !== text) { console.error(`${path.relative(root, file)} is stale; run npm run build:locales.`); process.exit(1); }
  }
  // The app loads each dictionary with its own script tag (strict CSP, nothing loaded on the fly), before the translator.
  const html = fs.readFileSync(path.join(root, "src", "renderer", "index.html"), "utf8");
  for (const l of Object.keys(compiled)) {
    const at = html.indexOf(`<script src="locales/${l}.js"></script>`);
    if (at < 0 || at > html.indexOf('<script src="i18n.js"></script>')) { console.error(`src/renderer/index.html does not load locales/${l}.js before i18n.js.`); process.exit(1); }
  }
  console.log(`Locale reproduction passed (${Object.keys(compiled).join(", ")}).`);
} else {
  for (const [file, text] of Object.entries(outputs)) { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text); console.log(`Wrote ${path.relative(root, file)} (${Buffer.byteLength(text)} bytes).`); }
}
module.exports = { luaPattern, luaReplacement, appPattern, GAME_LOCALES, LANG_CODES };
