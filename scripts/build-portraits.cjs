"use strict";
// Lists the painted character portraits (src/renderer/art/portraits/*.webp) for the renderer,
// so the app only ever points at art that ships. File names: <race>-<sex>-<class>.webp,
// <race>-<sex>.webp or <class>-<sex>.webp, all lowercase letters (race and class without spaces).
// Usage: node scripts/build-portraits.cjs [--check]
const fs = require("node:fs"), path = require("node:path");
const dir = path.join(__dirname, "../src/renderer/art/portraits"), out = path.join(__dirname, "../src/renderer/portraits.js");
const NAME = /^[a-z]+-(?:male|female)(?:-[a-z]+)?\.webp$|^[a-z]+-(?:male|female)-[a-z]+\.webp$/;
function list() {
  const names = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith(".webp")).sort() : [];
  for (const n of names) if (!NAME.test(n)) throw Error(`Unexpected portrait file name: ${n}`);
  return names.map((n) => n.replace(/\.webp$/, ""));
}
function render(keys) {
  return `"use strict";\n// Generated by scripts/build-portraits.cjs from src/renderer/art/portraits. Do not edit.\nwindow.BF_PORTRAITS = Object.freeze(${JSON.stringify(keys)});\n`;
}
module.exports = { list, render };
if (require.main === module) {
  const text = render(list());
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(out) || fs.readFileSync(out, "utf8").replace(/\r\n/g, "\n") !== text) { console.error("src/renderer/portraits.js is out of date: run node scripts/build-portraits.cjs"); process.exit(1); }
    console.log("Portrait list is current.");
  } else { fs.writeFileSync(out, text); console.log(`Wrote ${list().length} portraits.`); }
}
