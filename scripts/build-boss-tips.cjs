"use strict";
// Writes addon/BackstageForever/BackstageForeverBossTips.lua from src/core/boss-tips.cjs (1.3, J13).
const fs = require("node:fs"), path = require("node:path");
const { TIPS, REVIEWED_RAID_TIPS } = require("../src/core/boss-tips.cjs");
const q = (s) => `'${String(s).replace(/\\/g, "\\\\").replace(/'/g, "\\'")}'`;
const lines = Object.entries(TIPS).sort(([a], [b]) => a.localeCompare(b)).map(([name, tip]) => {
  const raid = REVIEWED_RAID_TIPS[name];
  const value = raid ? `{tip=${q(tip)},instanceMap=${raid.instanceMap},npcId=${raid.npcId}}` : q(tip);
  return `    [${q(name.toLowerCase())}]=${value},`;
});
const out = ["-- Generated by scripts/build-boss-tips.cjs from src/core/boss-tips.cjs; do not edit by hand.",
  "-- Short boss tips (text only, no timers), shown once when you target a covered boss.", "BackstageForeverBossTips={", ...lines, "}", ""].join("\r\n");
const file = path.join(__dirname, "../addon/BackstageForever/BackstageForeverBossTips.lua");
fs.writeFileSync(file, out);
console.log(`Wrote ${path.relative(process.cwd(), file)} (${lines.length} tips).`);
